import { readFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { createElement } from "react";
import { renderToStaticMarkup } from "react-dom/server";
import { afterAll, describe, expect, it } from "vitest";
import i18n from "../i18n";
import enMap from "../locales/en/disease-map.json";
import plMap from "../locales/pl/disease-map.json";
import type { GuidelinePoints } from "../types/guidelinePoints";
import { GuidelinePointsBlock } from "./GeneratedGuidelinePoints";

/**
 * The generated block for every disease but FD. What must hold: the page's language picks the summaries,
 * questions and title, the quotation stays the English original, every point links to its source with the
 * credit its terms ask for, and the fixed "generated by AI, nobody approved it" notice is always there.
 */
const block: GuidelinePoints = {
  basis: "reviews",
  titleEn: "What reviews of the literature say about diagnosis – to show your doctor",
  titlePl: "Co mówią przeglądy literatury o rozpoznaniu – do pokazania lekarzowi",
  noticeEn: "Generated by AI; nobody has approved it.",
  noticePl: "Wygenerowane przez AI; nikt tego nie zatwierdził.",
  sourceEn: "Quotations are from: Kaplan FS et al. Nobody has approved them.",
  sourcePl: "Cytaty pochodzą z: Kaplan FS i wsp. Nikt ich nie zatwierdzał.",
  credits: ["GeneReviews®, https://www.genereviews.org. Copyright © 1993–2026 University of Washington, Seattle."],
  generatedAt: "2026-11-24T00:00:00+00:00",
  points: [
    {
      id: "p1",
      quote: "If FOP is suspected, all elective procedures should be deferred until a definitive diagnosis is confirmed.",
      summaryEn: "If FOP is suspected, planned procedures should be put off until the diagnosis is confirmed.",
      summaryPl: "Jeśli podejrzewa się FOP, planowe zabiegi należy odłożyć do potwierdzenia rozpoznania.",
      questionEn: "Is any procedure planned for our child, and if so, should it wait?",
      questionPl: "Czy u naszego dziecka planowany jest jakiś zabieg, a jeśli tak, czy powinien poczekać?",
      section: "General recommendations",
      docId: "NBK558090",
      docTitle: "Fibrodysplasia Ossificans Progressiva",
      docYear: "continuously updated",
      docCitation: "Kaplan FS et al., Fibrodysplasia Ossificans Progressiva, GeneReviews (NBK558090)",
      docUrl: "https://www.ncbi.nlm.nih.gov/books/NBK558090/",
      docGrade: "B",
      licence: "restricted",
      credit: "GeneReviews®, https://www.genereviews.org. Copyright © 1993–2026 University of Washington, Seattle.",
    },
  ],
};

async function render(locale: "en" | "pl") {
  await i18n.changeLanguage(locale);
  return renderToStaticMarkup(createElement(GuidelinePointsBlock, { block }));
}

afterAll(async () => {
  await i18n.changeLanguage("en");
});

describe("generated guideline points", () => {
  it("shows the Polish summaries, question and title on the Polish page, with the English quote", async () => {
    const html = await render("pl");
    expect(html).toContain("Co mówią przeglądy literatury o rozpoznaniu");
    expect(html).toContain("planowe zabiegi należy odłożyć");
    expect(html).toContain("czy powinien poczekać?");
    expect(html).toContain('<q lang="en">If FOP is suspected');
    expect(html).toContain((plMap as Record<string, string>).askGeneratedNotice);
  });

  it("shows the English text, the source link and the GeneReviews credit on the English page", async () => {
    const html = await render("en");
    expect(html).toContain("What reviews of the literature say about diagnosis");
    expect(html).toContain('href="https://www.ncbi.nlm.nih.gov/books/NBK558090/"');
    expect(html).toContain("University of Washington");
    expect(html).toContain((enMap as Record<string, string>).askGeneratedNotice);
    expect(html).not.toContain("summaryPl");
  });

  it("the fixed notice says AI made it and nobody approved it, in both languages", () => {
    expect((enMap as Record<string, string>).askGeneratedNotice).toMatch(/AI.*Nobody.*approved/s);
    expect((plMap as Record<string, string>).askGeneratedNotice).toMatch(/AI.*Nikt.*zatwierdził/s);
  });

  it("FD keeps its hand-written block; every other disease gets the generated one", () => {
    const source = readFileSync(fileURLToPath(new URL("./ParentDiseaseMap.tsx", import.meta.url)), "utf8");
    expect(source).toMatch(/\{isFd \? \(\s*<div className="dmap-ask">/);
    expect(source).toContain("<GeneratedGuidelinePoints slug={slug} />");
  });
});
