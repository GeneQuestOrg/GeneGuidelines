"""The publishable shape of a guideline-points block, with its titles, links, credits and source note written by code, not by a model.

The note is fixed text on purpose: whether a point sounds approved is the one thing a model must never get to word. It names every document a quote came from and says plainly that the summaries and questions are AI-written and that nobody approved them.

Titles follow what the points rest on (``sources.block_basis``): only a block whose every point comes from a consensus statement or practice guideline may say "the guideline"; a block resting on reviews (GeneReviews included) says so.

Every point links to its source. A source without an open licence is quoted only briefly (``RESTRICTED_QUOTE_MAX_CHARS``, enforced by the verbatim check); GeneReviews' terms also ask for its source and copyright credit with every copy, which each GeneReviews point carries.
"""

from __future__ import annotations

from typing import Any

from .models import SourceDoc
from .sources import block_basis

TITLES = {
    "guideline": ("What the guideline says about diagnosis – to show your doctor", "Co mówi wytyczna o rozpoznaniu – do pokazania lekarzowi"),
    "guideline+reviews": ("What the guideline and reviews of the literature say about diagnosis – to show your doctor", "Co mówią wytyczna i przeglądy literatury o rozpoznaniu – do pokazania lekarzowi"),
    "reviews": ("What reviews of the literature say about diagnosis – to show your doctor", "Co mówią przeglądy literatury o rozpoznaniu – do pokazania lekarzowi"),
}
NOTICE_EN = "Generated by AI; nobody has approved it."
NOTICE_PL = "Wygenerowane przez AI; nikt tego nie zatwierdził."


def citation(doc: SourceDoc) -> str:
    first = (doc.authors or "").split(",")[0].strip()
    who = f"{first} et al., " if first else ""
    ids = f"PMID {doc.pmid}" if doc.pmid else (doc.bookshelf or doc.doc_id)
    where = f"{doc.book or doc.journal} {doc.year}".strip()
    return f"{who}{doc.title.rstrip('.')}, {where} ({ids})" if where else f"{who}{doc.title.rstrip('.')} ({ids})"


def published_block(record: dict[str, Any], docs: list[SourceDoc]) -> dict[str, Any] | None:
    """The block as a page would render it, or None when the record may not be published."""
    by_id = {d.doc_id: d for d in docs}
    accepted = [p for p in record.get("accepted") or [] if p["doc_id"] in by_id]
    basis = block_basis(by_id[p["doc_id"]].grade for p in accepted)
    if not record.get("publish") or not basis:
        return None
    used = [by_id[i] for i in dict.fromkeys(p["doc_id"] for p in accepted)]
    cites = "; ".join(citation(d) for d in used)
    credits = list(dict.fromkeys(d.credit for d in used if d.credit))
    title_en, title_pl = TITLES[basis]
    return {
        "basis": basis,
        "title_en": title_en,
        "title_pl": title_pl,
        "notice_en": NOTICE_EN,
        "notice_pl": NOTICE_PL,
        "points": [
            {
                **{k: p[k] for k in ("id", "doc_id", "section", "quote", "summary_en", "summary_pl", "question_en", "question_pl")},
                "doc_title": by_id[p["doc_id"]].title,
                "doc_year": by_id[p["doc_id"]].year,
                "doc_citation": citation(by_id[p["doc_id"]]),
                "doc_url": by_id[p["doc_id"]].url,
                "doc_grade": by_id[p["doc_id"]].grade,
                "pmid": by_id[p["doc_id"]].pmid,
                "licence": "open" if by_id[p["doc_id"]].open_licence else "restricted",
                "credit": by_id[p["doc_id"]].credit,
            }
            for p in accepted
        ],
        "sources": [{"doc_id": d.doc_id, "citation": citation(d), "url": d.url, "grade": d.grade, "licence": d.license, "credit": d.credit} for d in used],
        "credits": credits,
        "source_en": f"Quotations are from: {cites}. The summaries and questions were written by AI (Claude) and checked by a second AI model and by a word-for-word match with the source text. Nobody, neither the authors of these documents nor a clinician, has reviewed or approved them." + (" " + " ".join(credits) if credits else ""),
        "source_pl": f"Cytaty pochodzą z: {cites}. Streszczenia i pytania napisała sztuczna inteligencja (Claude); sprawdził je drugi model AI oraz dosłowne porównanie z tekstem źródła. Nikt – ani autorzy tych dokumentów, ani lekarz – ich nie przeglądał ani nie zatwierdzał." + (" " + " ".join(credits) if credits else ""),
    }
