"""The two Sonnet bricks that read the whole documents (``select`` and the ``quote`` writer) share one prompt cache.

A cache entry is the exact prefix of the request: the same model, the same system prompt, the same response schema and the same effort, then the documents. So both bricks use the system prompt and the response schema below, the documents block is the cached prefix, and each brick's own instruction comes after it. The response schema has a field for each brick; a brick fills its own and leaves the other empty.

Paragraphs are numbered per document (``¶1``, ``¶2``, …), so a model can point at a place without copying text; code reads the text from the location.
"""

from __future__ import annotations

from collections.abc import Iterable

from pydantic import BaseModel, ConfigDict, Field

from ..models import SourceDoc
from ..sources import GRADE_LABEL

READER_SYSTEM = """You read guideline-grade documents about one rare disease for a block of a web page for parents: "What the guideline says about diagnosis – to show your doctor". Each point of the block puts a passage from a document, copied word for word, next to a plain-language summary and one open question the parent can take to the doctor. The page orients and asks; it never advises. It is generated by AI and nobody has approved it.

The documents come first, each in a <document> tag with an id, a grade, a year and a licence:
- grade A: consensus statement or clinical practice guideline;
- grade B: GeneReviews chapter;
- grade C: other clinical review.
Every paragraph is numbered within its document (¶1, ¶2, …). Your task follows the documents. Answer in the response format; fill only the field your task names and leave the other empty."""


class Location(BaseModel):
    """A place in a document: a paragraph and a short phrase that picks out one statement in it."""

    model_config = ConfigDict(extra="ignore", str_strip_whitespace=True)

    doc_id: str = Field(..., description="id of the document, exactly as in its <document id=...> tag")
    paragraph: int = Field(..., description="the paragraph number shown as ¶n in that document")
    anchor: str = Field(..., description="the shortest phrase, copied word for word from that paragraph, that occurs only once in it and picks out the statement")
    reason: str = Field(..., description="what goes wrong for the family if they do not know this statement, in one sentence")


class QuotedPassage(BaseModel):
    model_config = ConfigDict(extra="ignore", str_strip_whitespace=True)

    id: str = Field(..., description="id of the location the quote is for")
    quote: str = Field(..., description="consecutive whole sentences copied word for word from the location's paragraph")


class DocumentReading(BaseModel):
    """The shared response schema of the document-reading bricks."""

    model_config = ConfigDict(extra="ignore")

    locations: list[Location] = Field(..., description="filled by the selection task; empty otherwise")
    quotes: list[QuotedPassage] = Field(..., description="filled by the quoting task; empty otherwise")


def render_numbered_documents(docs: Iterable[SourceDoc]) -> str:
    """The documents block with numbered paragraphs. Identical for every call of one run, so it is the cached prefix."""
    parts: list[str] = []
    for d in docs:
        licence = "open" if d.open_licence else f"restricted (quotes at most {d.quote_limit} characters)"
        lines = [
            f'<document id="{d.doc_id}" grade="{d.grade}" kind="{GRADE_LABEL.get(d.grade, "")}" year="{d.year}" licence="{licence}">',
            f"<title>{d.title}</title>",
        ]
        last: str | None = None
        for n, p in enumerate(d.paragraphs, 1):
            if p.section != last:
                lines.append(f"\n## {p.section or '(no heading)'}")
                last = p.section
            lines.append(f"¶{n} {p.text}\n")
        lines.append("</document>")
        parts.append("\n".join(lines))
    return "\n\n".join(parts)


__all__ = ["READER_SYSTEM", "DocumentReading", "Location", "QuotedPassage", "render_numbered_documents"]
