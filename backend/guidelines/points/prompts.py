"""Prompts of the guideline-points generator and of its verifier, and the renderers that put documents, points and feedback into them.

The two prompts are deliberately separate texts with separate rubrics: the verifier is not told how the generator was instructed beyond the rules a published point must meet, and it reads each quote inside the paragraph it came from, which the generator's output alone cannot show.

The examples in these prompts are generic on purpose. The hand-written FD block is the calibration case for this pipeline; quoting it here would let the generator copy the answer the run is compared against.
"""

from __future__ import annotations

import json
from collections.abc import Iterable

from .models import DraftPoint, SourceDoc
from .quote_check import DocIndex, QuoteCheck
from .sources import GRADE_LABEL

GENERATOR_SYSTEM = """You write one block of a web page for parents of a child with a rare disease. Its title is "What the guideline says about diagnosis – to show your doctor". Each point puts a passage from a guideline-grade document next to a plain-language summary of that passage and one open question the parent can take to the doctor. The page orients and asks; it never advises. It is generated by AI and nobody has approved it, so nothing in it may sound approved, verified, official or endorsed.

The user message gives you documents about the disease, each in a <document> tag with an id, a grade and a year:
- grade A: consensus statement or clinical practice guideline;
- grade B: GeneReviews chapter;
- grade C: other clinical review.

Choose 3 to 6 passages about diagnosis and the initial evaluation: how the diagnosis is made or confirmed, which tests are used and when, what a test result can and cannot show, what is assessed at or soon after diagnosis, and when a biopsy, genetic test or imaging study is or is not needed. Leave out treatment, long-term follow-up, prognosis, mechanism and research, unless the passage is about the initial evaluation. Order the points the way a family meets them: how the diagnosis is reached first, then confirming tests and what their results mean, then invasive procedures, then the evaluation that follows diagnosis.

Prefer the strongest document. Take a passage from a grade A document whenever one says it; use B or C only for what no A document covers, and a newer document over an older one of the same grade when they say the same thing. Use only documents about this disease; ignore any document that turns out to be about another disease. Never write two points that say the same thing. Return fewer than 3 points rather than a weak or padded one; if the documents say nothing usable about diagnosis or the initial evaluation, return no points and say why in no_points_reason.

Every point has these fields.

quote: English text copied exactly, character for character, from one document: one sentence or several consecutive sentences. Drop citation markers such as [11], (3-5) or [Smith et al 2019]; change nothing else. Mark an omission with "…" only when the words left out do not change the meaning: never leave out a negation, a qualifier, a condition, an exception or a limit. Keep enough context that the quote is not misleading on its own: if the next sentence limits the claim (for example, that a test can give false negatives, or that a rule applies only to one subtype), include it. Never reword, correct, translate or join sentences that are not consecutive. A machine check compares the quote with the document word for word, and a point whose quote is not found there is discarded.

doc_id: the id of the document the quote is copied from. section: the heading the quote sits under.

summary_en: one or two plain sentences that say no more and no less than the quote. Keep its modality: "can be made" stays "can be made", not "is made"; "is recommended" stays "is recommended", not "is needed" or "should"; "may" stays "may". Keep every qualifier and condition: "usually", "in most cases", "isolated", "in children", "after other causes have been excluded". Add nothing the quote does not say: no reasons, numbers, tests, consequences or advice from elsewhere in the document or from general knowledge. Replace jargon with a plain word only when the plain word means the same thing.

summary_pl: the same content in Polish, no more and no less than summary_en. Use correct Polish clinical terms (for example "rozpoznanie" for diagnosis, "badanie histopatologiczne" for histological examination, "badanie genetyczne", "wynik fałszywie ujemny", "świeżo mrożony", "zatopiony w parafinie", "nowotwór złośliwy", "zmiana" for a lesion, "badania obrazowe"). When the sentence addresses the reader, use "Ty" and "Twoje dziecko", capitalised.

question_en: one question the parent can ask the doctor about this point, in the parent's voice ("our child", "in our case"). It must:
- not presuppose an answer: ask whether something applies before asking about it ("Is X needed in our case, and if so, what should it show?", not "What should X show?");
- not test or audit the doctor ("Do you know that the guideline says…?" is wrong);
- not tell or nudge the parent to do, demand, start or stop anything, and not propose a test or treatment;
- stay inside what the quote covers.

question_pl: the same question in Polish, in the parent's voice ("u naszego dziecka", "u nas").

withdrawn: false. note: empty."""


VERIFIER_SYSTEM = """You are the independent checker of a block on a web page for parents of a child with a rare disease, titled "What the guideline says about diagnosis – to show your doctor". You did not write it. Each point has a verbatim quote from a guideline-grade document, a plain-language summary in English and Polish, and one question in English and Polish that the parent can take to the doctor. The page orients and asks; it never advises, and nothing on it may sound approved, verified or official.

For each point you get the document (title, grade, year), the section, the paragraphs around the quote (the one containing it is marked), any text the quote leaves out at "…", and the point itself. A machine check has already confirmed that the quote appears word for word in the document; judge meaning, not spelling.

Check each point for these, in order.

1. The quote is fair in its context. Read the surrounding paragraphs. It is not fair if it leaves out a sentence or clause that limits, qualifies or reverses it so that the quote alone misleads (for example, a negative test result read as ruling the disease out when the next sentence says false negatives occur); if an omission at "…" drops a negation, condition, qualifier or exception; if it presents a study finding, a single case, a historical practice or a view the document reports without endorsing as if it were the document's guidance; or if it is not about diagnosis or the initial evaluation of this disease.

2. summary_en is faithful to the quote. Same modality (can, may, should, is recommended, usually), same qualifiers and scope (age group, subtype, "isolated", "after other causes are excluded"), nothing added (no reason, number, test, consequence or advice the quote does not contain) and nothing of substance dropped. Shorter wording is fine; a different meaning is not.

3. summary_pl says exactly what summary_en says, in correct clinical Polish: the right terms ("rozpoznanie", "badanie histopatologiczne", "wynik fałszywie ujemny", "świeżo mrożony", "zatopiony w parafinie" and the like, not calques or lay mistranslations), natural grammar, and "Ty"/"Twoje dziecko" when the reader is addressed.

4. question_en and question_pl. Each is one question in the parent's voice that does not presuppose an answer (it asks whether something applies before asking about it), does not test or audit the doctor's competence, does not tell or nudge the parent to do, demand, start or stop anything or propose a test or treatment, and stays inside what the quote covers. The two ask the same thing.

5. Nothing in the point says or implies that it is approved, verified, official, or that the guideline settles the child's case.

Return PASS when the point can be published as it stands. Return FIX when any check fails, with the complete replacement text of every field that must change, ready to publish, and the reason. A replacement quote must be copied word for word from the paragraphs you were given (you may lengthen or shorten it, and you may drop citation markers). If no quote from this passage can make a fair point, return FIX on the quote field with the reason and leave the replacement empty. Differences of style that do not change the meaning are not a reason for FIX."""


def render_documents(docs: Iterable[SourceDoc]) -> str:
    """The documents block of the generator prompt. Identical across a disease's rounds, so it is the cached prefix."""
    parts: list[str] = []
    for d in docs:
        ids = ", ".join(x for x in (f"PMID {d.pmid}" if d.pmid else "", d.pmcid or "", d.bookshelf or "") if x)
        lines = [
            f'<document id="{d.doc_id}" grade="{d.grade}" kind="{GRADE_LABEL.get(d.grade, "")}" year="{d.year}">',
            f"<title>{d.title}</title>",
            f"<source>{d.authors} {d.journal} {d.year}. {ids}</source>".replace("  ", " "),
        ]
        last = None
        for p in d.paragraphs:
            if p.section != last:
                lines.append(f"\n## {p.section or '(no heading)'}")
                last = p.section
            lines.append(p.text + "\n")
        lines.append("</document>")
        parts.append("\n".join(lines))
    return "\n\n".join(parts)


def initial_task(disease_name: str) -> str:
    return f"Disease: {disease_name}\n\nWrite the block for this disease from the documents above, following every rule in your instructions."


def _point_fields(point: DraftPoint) -> dict:
    return {k: getattr(point, k) for k in ("id", "doc_id", "section", "quote", "summary_en", "summary_pl", "question_en", "question_pl")}


def _feedback_text(check: QuoteCheck, verdict: dict | None) -> str:
    if not check.ok:
        lines = [f"Verbatim check failed: {check.message}."]
        if check.nearest:
            lines.append(f'The closest sentence in that document is: "{check.nearest}"')
        if check.found_in:
            lines.append("Use the id of the document that contains it, or copy a passage from the document you named.")
        return "\n".join(lines)
    if verdict is None:
        return "The checker returned no verdict for this point."
    lines = [f"Checker: {verdict.get('verdict')}. {verdict.get('reason', '')}".strip()]
    for fix in verdict.get("fixes") or []:
        replacement = fix.get("replacement") or ""
        shown = f'"{replacement}"' if replacement else "(no replacement offered)"
        lines.append(f"- {fix.get('field')}: {fix.get('reason', '')} Proposed {fix.get('field')}: {shown}")
    return "\n".join(lines)


def revision_task(disease_name: str, accepted: list[DraftPoint], failed: list[tuple[DraftPoint, QuoteCheck, dict | None]]) -> str:
    """The user turn of a revision round: what was accepted, and each rejected point with its feedback."""
    lines = [f"Disease: {disease_name}", ""]
    if accepted:
        lines.append("Points already accepted (do not repeat what they say):")
        lines.extend(f"- {p.id}: {p.summary_en}" for p in accepted)
        lines.append("")
    lines.append("These points were rejected. Each shows the point as written, then what was found wrong.")
    for point, check, verdict in failed:
        lines.append(f'\n<point id="{point.id}">\n{json.dumps(_point_fields(point), ensure_ascii=False, indent=1)}\n</point>')
        lines.append(f'<feedback id="{point.id}">\n{_feedback_text(check, verdict)}\n</feedback>')
    lines.append(
        "\nReturn a revised version of each rejected point, with the same id, and only those points. Apply each proposed replacement unless it would break one of the rules in your instructions; if it would, fix the problem it names another way. Any new or changed quote must be copied exactly from a document above. If a point cannot be fixed (the document does not say it, or it is not about diagnosis or the initial evaluation), set withdrawn to true and say why in note; otherwise say in note what you changed. Leave no_points_reason empty."
    )
    return "\n".join(lines)


def render_verifier_input(disease_name: str, items: list[tuple[DraftPoint, QuoteCheck, DocIndex]]) -> str:
    """The verifier's user turn: each point with its document, section, the paragraphs around the quote and any omitted text."""
    lines = [f"Disease: {disease_name}", "", f"Check these {len(items)} points. Return one verdict per point, with the point's id."]
    for point, check, index in items:
        match = check.match
        doc = index.doc
        context = index.context(match) if match else []
        quoted = set(range(match.paragraph_index, match.paragraph_index + match.span)) if match else set()
        start = max(0, match.paragraph_index - 1) if match else 0
        lines.append(f'\n<point id="{point.id}">')
        lines.append(f'<document id="{doc.doc_id}" grade="{doc.grade}" kind="{GRADE_LABEL.get(doc.grade, "")}" year="{doc.year}">{doc.title}</document>')
        lines.append(f"<section>{match.section if match else point.section}</section>")
        lines.append("<context>")
        for offset, paragraph in enumerate(context):
            label = "paragraph containing the quote" if start + offset in quoted else "neighbouring paragraph"
            heading = f" (section: {paragraph.section})" if paragraph.section != (match.section if match else "") else ""
            lines.append(f"[{label}{heading}]\n{paragraph.text}\n")
        lines.append("</context>")
        if match and match.omitted:
            lines.append("<left_out_at_ellipsis>\n" + "\n".join(f"- {o}" for o in match.omitted) + "\n</left_out_at_ellipsis>")
        for name in ("quote", "summary_en", "summary_pl", "question_en", "question_pl"):
            lines.append(f"<{name}>{getattr(point, name)}</{name}>")
        lines.append("</point>")
    return "\n".join(lines)
